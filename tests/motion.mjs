import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
let passed = 0; const failures = [];
const check = (name, ok) => { if (ok) passed++; else { failures.push(name); console.error('  ✗', name); } };
const css = readFileSync(join(here, '../web/styles.css'), 'utf8');
const app = readFileSync(join(here, '../web/app.js'), 'utf8');
console.log('RH—MUSIC · Motion System tests\n');
check('motion tokens exist', ['--motion-instant','--motion-micro','--motion-ui','--motion-popover','--motion-modal','--motion-panel','--motion-page'].every((t) => css.includes(t)));
check('easing tokens exist', ['--ease-standard','--ease-out','--ease-in-out','--ease-soft'].every((t) => css.includes(t)));
check('interactive elements share transitions', css.includes(':where(button, .btn, .chip, .tab, .side-item, .ctrl, .icon-btn, .row-btn, .card, .track, .sheet-item, .queue-panel, .search-field)'));
check('press feedback is unified', css.includes(':where(button, .btn, .chip, .ctrl, .icon-btn, .row-btn, .tab, .side-item, .sheet-item):active'));
check('desktop hover presets exist', css.includes('@media (hover: hover) and (pointer: fine)') && css.includes('.card:hover'));
check('player hide is animated before hidden', app.includes('playerHideTimer') && app.includes('player.classList.add(\'is-hidden\')') && app.includes('setTimeout(() => {'));
check('player starts hidden when shown', css.includes('@starting-style') && css.includes('.mini-now'));
check('sheet and drawer use motion tokens', css.includes('transition: transform var(--motion-panel) var(--ease-soft), visibility var(--motion-panel)') && css.includes('.sheet-panel { transition: transform var(--motion-panel)'));
check('progress fill remains visible', css.includes('.seek::-webkit-slider-runnable-track') && css.includes('var(--fill, 0%)'));
check('page content reveal is capped', css.includes('rh-page-in') && css.includes('#page > :where'));
check('list stagger is capped', css.includes('.track-list .track:nth-child(n+11)'));
check('reduced motion disables decoration', css.includes('@media (prefers-reduced-motion: reduce)') && css.includes('animation-duration: .001ms !important'));
check('audio/AutoMix code untouched', !app.includes('motionSystemAudio') && app.includes('function streamUrl(track)'));
console.log(`\n${passed} passed, ${failures.length} failed`);
if (failures.length) process.exit(1);
