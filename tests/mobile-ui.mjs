import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, '../web/app.js'), 'utf8');
const css = readFileSync(join(here, '../web/redesign.css'), 'utf8');
const html = readFileSync(join(here, '../web/index.html'), 'utf8');
const cover = readFileSync(join(here, '../web/beat-cover.js'), 'utf8');
let passed = 0; const failures = [];
const check = (name, ok) => { if (ok) passed++; else { failures.push(name); console.error('  ✗', name); } };
console.log('RH—MUSIC · mobile UI audit tests\n');
check('нет полупрозрачной плашки у drag-handle', !/\.drag-handle\s*\{[^}]*background:\s*rgba\(255,\s*255,\s*255,\s*\.16\)/.test(css));
check('у карточек нет декоративного ::after', !/\.card::after\s*\{/.test(css));
check('мобильный scrim прозрачный', /\.scrim\s*\{[^}]*background:\s*transparent/.test(css));
check('на мобильном убраны backdrop-filter и clip-path', /html\[data-ui="mobile"\] \.now-playing[^{]*\{[^}]*backdrop-filter:\s*none/.test(css) && !/clip-path:\s*inset\(0 round 28px\)/.test(css));
check('пульсация обложки вынесена во внутренний слой', /np-art-beat/.test(html) && /npArtBeat/.test(cover));
check('карточки и заголовки не плодят треугольники на телефоне', /card-play\s*\{\s*display:\s*none/.test(css) && /section-title::before\s*\{\s*display:\s*none/.test(css));
check('есть мгновенная подсветка нажатия', /is-pressed/.test(app) && /\.is-pressed/.test(css));
check('переход по маршруту закрывает оверлеи', /if \(S\.lyricsOpen\) openLyricsSheet\(false\)/.test(app) && /if \(S\.npOpen\) openNowPlaying\(false\)/.test(app));
check('вход и переходы открываются сверху', /scrollRestoration = 'manual'/.test(app) && /window\.scrollTo\(0, 0\)/.test(app));
console.log(`\n${passed} passed, ${failures.length} failed`);
if (failures.length) process.exit(1);
