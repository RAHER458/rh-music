import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
let passed=0; const failures=[];
const check=(n,c,e='')=>{if(c){passed++;return;} failures.push(n+(e?' — '+e:'')); console.error('  ✗',n,e);};
const html=readFileSync(join(here,'../web/index.html'),'utf8');
const app=readFileSync(join(here,'../web/app.js'),'utf8');
const source=readFileSync(join(here,'../web/automix2/controller.js'),'utf8');
const cache=readFileSync(join(here,'../web/automix2/cache.js'),'utf8');
const win={};
new Function('window','document',source)(win,{createElement:()=>({})});
const API=win.RH_AUTOMIX2;
console.log('RH—MUSIC · Auto Mix Beta 2.0 tests\n');
check('Beta2 global exists', !!API);
check('Beta2 button removed from UI', !html.includes('id="autoMix2Btn"'));
check('Beta2 chip removed from UI', !html.includes('id="npAutoMix2"'));
check('Beta2 controller not loaded by page', !html.includes('automix2/controller.js') && !html.includes('automix2/cache.js'));
check('Beta2 not initialized by app', !/\n\s*initAutoMix2\(\);/.test(app));
check('Beta2 does not intercept player', !app.includes('RH_AUTOMIX2.onTrackStarted') && !app.includes('RH_AUTOMIX2.pause()') && !app.includes('RH_AUTOMIX2.seek(target)'));
check('Beta2 code is preserved', source.length > 1000 && cache.length > 100);
check('Railway API configured', source.includes('https://automix2-api-production.up.railway.app'));
check('preview WAV is generated', source.includes('encodePreviewWav') && source.includes('RIFF'));
check('Railway analysis with local fallback', source.includes('analyzeRemote') && source.includes('Railway analysis fallback'));
check('Railway planner with local fallback', source.includes('planTransitionRemote') && source.includes('Railway plan fallback'));
check('Beta2 has two real decks', source.includes('createBufferSource') && source.includes('makeDeck'));
check('Beta2 has bass swap and equal-power fade', source.includes('beta-bass-swap') && source.includes('Math.cos(t * Math.PI / 2)'));
check('Beta2 has queue order after current index', source.includes('(idx + off) % q.length'));
check('Beta2 has analysis cache', cache.includes('rh_automix2') && cache.includes('MAX_ENTRIES'));
check('cache records are unwrapped before use', source.includes('analysis && analysis.analysis') && source.includes('!Array.isArray(analysis.downbeats)'));
check('nearestDownbeat tolerates missing grids', source.includes("!Array.isArray(analysis.downbeats)") && source.includes('return Math.max(0, Number(time) || 0)'));
check('release closes AudioContext and clears mixer', source.includes('state.ctx.close()') && source.includes('state.ctx = null; state.mixer = null'));
check('re-enable closes an existing context', source.includes("if (state.ctx) { try { state.ctx.close(); } catch (_) {} state.ctx = null; state.mixer = null; }"));
check('Beta2 release API preserved for future', source.includes('function releaseToStandard'));
check('seek invalidation API preserved for future', source.includes('function invalidatePlan'));
check('transition failure stops all decks before restoring', source.includes("state.mixer && state.mixer.stop()") && source.includes('beta transition:'));
check('adoption failure cannot silently desync UI', source.includes('adoption failed:'));
check('DEGRADED carries a concrete reason', source.includes('function degrade') && source.includes('reason: state.error'));
check('empty queue becomes READY with retry', source.includes('Ожидание следующего трека') && source.includes('retryLater'));
check('no-transition is not forced', source.includes('Planner: no transition') && source.includes("remote.noTransition"));
check('Beta2 adopts through RH-MUSIC state', app.includes("adoptAiTrack(track, strategy, 'Auto Mix Beta 2.0')"));
console.log(`\n${passed} passed, ${failures.length} failed`);
if(failures.length) process.exit(1);
