import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
let passed=0; const failures=[];
const check=(n,c,e='')=>{if(c){passed++;return;} failures.push(n+(e?' — '+e:'')); console.error('  ✗',n,e);};
const html=readFileSync(join(here,'../web/index.html'),'utf8');
const app=readFileSync(join(here,'../web/app.js'),'utf8');
const source=readFileSync(join(here,'../web/automix2/controller.js'),'utf8');
const cache=readFileSync(join(here,'../web/automix2/cache.js'),'utf8');
const win={};
new Function('window','document',source)(win,{createElement:()=>({})});
const API=win.RH_AUTOMIX2;
console.log('RH—MUSIC · Auto Mix Beta 2.0 tests\n');
check('Beta2 global exists', !!API);
check('Beta2 button exists once', (html.match(/id="autoMix2Btn"/g)||[]).length===1);
check('Beta2 chip exists', html.includes('id="npAutoMix2"'));
check('Beta2 controller loaded', html.includes('automix2/controller.js'));
check('Beta2 cache loaded', html.includes('automix2/cache.js'));
check('Beta2 is initialized', /\n\s*initAutoMix2\(\);/.test(app));
check('Railway API configured', source.includes('https://automix2-api-production.up.railway.app'));
check('preview WAV is generated', source.includes('encodePreviewWav') && source.includes('RIFF'));
check('Railway analysis with local fallback', source.includes('analyzeRemote') && source.includes('Railway analysis fallback'));
check('Railway planner with local fallback', source.includes('planTransitionRemote') && source.includes('Railway plan fallback'));
check('Beta2 has two real decks', source.includes('createBufferSource') && source.includes('makeDeck'));
check('Beta2 has bass swap and equal-power fade', source.includes('beta-bass-swap') && source.includes('Math.cos(t * Math.PI / 2)'));
check('Beta2 has queue order after current index', source.includes('(idx + off) % q.length'));
check('Beta2 has analysis cache', cache.includes('rh_automix2') && cache.includes('MAX_ENTRIES'));
check('Beta2 is mutually exclusive with AI AutoMix', app.includes('Сначала выключите Auto Mix Beta 2.0') && app.includes('Сначала выключите AI AutoMix'));
check('Beta2 routes Play/Pause and seek', app.includes('RH_AUTOMIX2.pause()') && app.includes('RH_AUTOMIX2.seek(target)'));
check('Beta2 adopts through RH-MUSIC state', app.includes("adoptAiTrack(track, strategy, 'Auto Mix Beta 2.0')"));
console.log(`\n${passed} passed, ${failures.length} failed`);
if(failures.length) process.exit(1);
