import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, '../web/index.html'), 'utf8');
const css = readFileSync(join(here, '../web/redesign.css'), 'utf8');
let passed = 0; const failures = [];
const check = (name, ok) => { if (ok) passed++; else { failures.push(name); console.error('  ✗', name); } };
console.log('RH—MUSIC · global redesign tests\n');
check('redesign.css подключён после базовых стилей', /styles\.css[^>]*>[\s\S]{0,200}redesign\.css/.test(html));
check('единая тёмная палитра и акценты', /--bg: #05060a/i.test(css) && /--blue: #7c8cff/i.test(css) && /--violet: #b06cff/i.test(css));
check('единые радиусы, тени и типографика', /--r-xl: 30px/.test(css) && /--font-display/.test(css) && /--shadow-md/.test(css));
check('переработаны карточки и трек-строки', /\.card \{/.test(css) && /\.track-card/.test(css) && /\.track\.is-current/.test(css));
check('переработаны плеер и Now Playing', /\.now-playing \{/.test(css) && /\.np-art \{/.test(css) && /\.player \{/.test(css));
check('переработаны sidebar, tabbar и очереди', /\.sidebar \{/.test(css) && /\.tabbar \{/.test(css) && /\.queue-panel \{/.test(css));
check('переработаны поиск, библиотека, профиль и авторизация', /\.search-field \{/.test(css) && /\.detail \{/.test(css) && /\.profile-head \{/.test(css) && /\.auth-card \{/.test(css));
check('адаптивность и reduced motion', /@media \(max-width: 700px\)/.test(css) && /@media \(min-width: 1024px\)/.test(css) && /prefers-reduced-motion/.test(css));
console.log(`\n${passed} passed, ${failures.length} failed`);
if (failures.length) process.exit(1);
